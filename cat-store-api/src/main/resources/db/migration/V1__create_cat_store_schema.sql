CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    phone VARCHAR(40)
);

CREATE TABLE cats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    breed VARCHAR(80) NOT NULL,
    age_months INTEGER NOT NULL CHECK (age_months BETWEEN 0 AND 360),
    description VARCHAR(1000) NOT NULL,
    price_cents BIGINT NOT NULL CHECK (price_cents BETWEEN 1 AND 900719925474099),
    status VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'RESERVED', 'SOLD', 'ARCHIVED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE store_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'PLACED' CHECK (status IN ('PLACED', 'FULFILLED', 'CANCELLED')),
    total_cents BIGINT NOT NULL CHECK (total_cents > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES store_orders (id) ON DELETE CASCADE,
    cat_id BIGINT NOT NULL REFERENCES cats (id) ON DELETE RESTRICT,
    unit_price_cents BIGINT NOT NULL CHECK (unit_price_cents > 0),
    cat_name VARCHAR(80) NOT NULL,
    cat_breed VARCHAR(80) NOT NULL,
    UNIQUE (order_id, cat_id)
);

CREATE INDEX idx_cats_status ON cats (status);
CREATE INDEX idx_orders_customer_created ON store_orders (customer_id, created_at DESC);
CREATE INDEX idx_order_items_cat ON order_items (cat_id);

